import {readFile, writeFile} from 'node:fs/promises';
import peggy from 'peggy';

const grammar = await readFile(new URL('../src/parser/query.pegjs', import.meta.url), 'utf8');
const source = peggy.generate(grammar, {format: 'es', output: 'source'});
await writeFile(
  new URL('../src/parser/query-parser.generated.ts', import.meta.url),
  `// @ts-nocheck -- generated by scripts/generate-query-parser.mjs\n${source}\n`,
);
